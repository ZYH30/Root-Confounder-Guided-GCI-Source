#!/usr/bin/env python3
"""Run the controlled adjustment-specification experiment reported in Table III.

Factual and counterfactual outcomes are generated by the same SCM with shared root
variables and node-level noise.  The intervention replaces T by T-delta and recursively
recomputes its descendants.  Every adjustment strategy uses the same datasets, splits,
and polynomial-ridge outcome estimator.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

THIS_FILE = Path(__file__).resolve()
EXPERIMENT_ROOT = THIS_FILE.parents[1]
sys.path.insert(0, str(EXPERIMENT_ROOT))

from gci_analysis.data_generators import GeneratorConfig, generate_case_dataset  # noqa: E402
from gci_analysis.fast_estimators import FastEvaluationConfig, evaluate_adjustment_set_fast  # noqa: E402
from gci_analysis.graph_cases import ADJUSTMENT_SET_LABELS, adjustment_sets_for_case, fmt_vars  # noqa: E402


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, default=EXPERIMENT_ROOT / "results" / "tables")
    parser.add_argument("--n-samples", type=int, default=1500)
    parser.add_argument("--n-datasets", type=int, default=10)
    parser.add_argument("--n-splits", type=int, default=10)
    parser.add_argument("--test-size", type=float, default=0.2)
    parser.add_argument("--delta-t", type=float, default=1.0)
    parser.add_argument("--noise-scale", type=float, default=0.5)
    parser.add_argument("--poly-degree", type=int, default=3)
    parser.add_argument("--ridge-alpha", type=float, default=1.0)
    parser.add_argument("--random-seed", type=int, default=2026)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    raw_frames = []

    for dataset_repeat in range(args.n_datasets):
        dataset_seed = args.random_seed + 10000 * dataset_repeat
        generator_config = GeneratorConfig(
            n_samples=args.n_samples,
            delta_t=args.delta_t,
            noise_scale=args.noise_scale,
            random_seed=dataset_seed,
        )
        evaluation_config = FastEvaluationConfig(
            n_repeats=args.n_splits,
            test_size=args.test_size,
            delta_t=args.delta_t,
            random_seed=dataset_seed,
            poly_degree=args.poly_degree,
            ridge_alpha=args.ridge_alpha,
        )

        for case_id in range(1, 5):
            data = generate_case_dataset(case_id, "additive_sine", generator_config)
            set_map = adjustment_sets_for_case(case_id)
            for strategy in ADJUSTMENT_SET_LABELS:
                variables = set_map[strategy]
                run = evaluate_adjustment_set_fast(data, variables, evaluation_config)
                run.insert(0, "dataset_repeat", dataset_repeat)
                run.insert(1, "case_id", case_id)
                run.insert(2, "adjustment_strategy", strategy)
                run.insert(3, "adjustment_variables", fmt_vars(variables))
                run.insert(4, "adjustment_set_size", len(variables))
                raw_frames.append(run)
            print(f"Finished dataset {dataset_repeat + 1}/{args.n_datasets}, Case {case_id}", flush=True)

    raw = pd.concat(raw_frames, ignore_index=True)
    group_cols = ["case_id", "adjustment_strategy", "adjustment_variables", "adjustment_set_size"]
    summary = (
        raw.groupby(group_cols, as_index=False)
        .agg(
            RMSE_MTEF_mean=("rmse_mtef", "mean"),
            RMSE_MTEF_sd=("rmse_mtef", "std"),
            Bias_MTEF_mean=("bias_mtef", "mean"),
            Bias_MTEF_sd=("bias_mtef", "std"),
            MAE_MTEF_mean=("mae_mtef", "mean"),
            RMSE_factual_mean=("rmse_factual", "mean"),
        )
    )
    summary["Case"] = summary["case_id"].map(lambda x: f"Case {x}")
    strategy_order = {name: i for i, name in enumerate(ADJUSTMENT_SET_LABELS)}
    summary["_strategy_order"] = summary["adjustment_strategy"].map(strategy_order)
    summary = summary.sort_values(["case_id", "_strategy_order"]).drop(columns="_strategy_order")

    display = summary[
        [
            "Case",
            "adjustment_strategy",
            "adjustment_variables",
            "adjustment_set_size",
            "RMSE_MTEF_mean",
            "RMSE_MTEF_sd",
            "Bias_MTEF_mean",
            "MAE_MTEF_mean",
        ]
    ].copy()
    display.columns = [
        "Case",
        "Adjustment strategy",
        "Adjustment variables",
        "Set size",
        "RMSE MTEF mean",
        "RMSE MTEF SD",
        "Bias MTEF mean",
        "MAE MTEF mean",
    ]
    display["RMSE MTEF"] = display.apply(
        lambda row: f"{row['RMSE MTEF mean']:.3f} $\\pm$ {row['RMSE MTEF SD']:.3f}",
        axis=1,
    )

    raw_path = args.output_dir / "synthetic_adjustment_baselines_raw.csv"
    summary_path = args.output_dir / "synthetic_adjustment_baselines_summary.csv"
    table_path = args.output_dir / "synthetic_adjustment_baselines_table.csv"
    tex_path = args.output_dir / "table_synthetic_adjustment_baselines.tex"
    config_path = args.output_dir / "synthetic_adjustment_baselines_config.json"

    raw.to_csv(raw_path, index=False)
    summary.to_csv(summary_path, index=False)
    table_columns = [
        "Case",
        "Adjustment strategy",
        "Adjustment variables",
        "Set size",
        "RMSE MTEF",
        "Bias MTEF mean",
        "MAE MTEF mean",
    ]
    display[table_columns].to_csv(table_path, index=False)
    display[table_columns].to_latex(tex_path, index=False, escape=False)

    config_payload = {
        "n_samples": args.n_samples,
        "n_datasets": args.n_datasets,
        "n_splits": args.n_splits,
        "test_size": args.test_size,
        "delta_t": args.delta_t,
        "noise_scale": args.noise_scale,
        "poly_degree": args.poly_degree,
        "ridge_alpha": args.ridge_alpha,
        "random_seed": args.random_seed,
    }
    with config_path.open("w", encoding="utf-8") as stream:
        json.dump(config_payload, stream, indent=2)

    print(f"Saved: {raw_path}")
    print(f"Saved: {summary_path}")
    print(f"Saved: {table_path}")
    print(f"Saved: {tex_path}")
    print(f"Saved: {config_path}")
    print(display[table_columns].to_string(index=False))


if __name__ == "__main__":
    main()
